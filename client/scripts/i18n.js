        if (savedLang && this.dictionary[savedLang]) {
            this.currentLanguage = savedLang;
        } else {
            const browserLang = navigator.language ? navigator.language.split('-')[0] : 'en';
            this.currentLanguage = this.dictionary[browserLang] ? browserLang : 'en';
        }
